public class IntergerDemo {
    public static void main(String[] args)
    {
        int anInt = 1234 ;
        byte aByte = 12;
        short aShort = 12345;
        long aLong = 123456789L;
        int anotherInt = anInt * 10000000 ;
        System.out.println("The value of int is " + anInt) ;
        System.out.println("The value of byte is " + aByte) ;
        System.out.println("The value of short is " + aShort) ;
        System.out.println("The value of long is " + aLong) ;
        System.out.println("The value of anotherInt is " + anotherInt) ;
    

    }
}